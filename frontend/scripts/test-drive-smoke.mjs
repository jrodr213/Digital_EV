import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

const base=process.env.EV_BASE_URL??'http://127.0.0.1:8000';
const browser=await chromium.launch({channel:process.env.EV_BROWSER??'chrome',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(60000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const snapshot=async()=>JSON.stringify(await Promise.all(['components','vehicles','results'].map(async path=>(await page.request.get(`${base}/api/${path}`)).json())));
const read=()=>page.getByTestId('drive-telemetry').evaluate(el=>Object.fromEntries([...el.attributes].filter(a=>a.name.startsWith('data-')).map(a=>[a.name.slice(5),a.value])));
try{
  const before=await snapshot();
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.getByLabel('Choose a car',{exact:true}).selectOption('team-ev-belt');
  await page.getByRole('button',{name:'Open car',exact:true}).click();
  await page.getByRole('button',{name:'Test drive',exact:true}).click();
  const drive=page.getByRole('dialog',{name:'Interactive test drive'});
  await drive.waitFor();
  assert.match(await drive.innerText(),/2 motors · RWD · 1:1/);
  await page.getByRole('button',{name:'Start driving',exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('[data-testid="drive-telemetry"]')?.getAttribute('data-time'))>1.5);
  const stationary=await read();
  assert.ok(Math.abs(+stationary.speed)<.04,`No-input speed: ${stationary.speed}`);
  assert.equal(+stationary.contacts,4);
  await page.keyboard.down('KeyW');
  await page.waitForFunction(start=>Number(document.querySelector('[data-testid="drive-telemetry"]')?.getAttribute('data-time'))>start+6,+stationary.time);
  await page.keyboard.up('KeyW');
  const moving=await read();console.log('Moving telemetry',moving);
  assert.ok(+moving.speed>.1,'Selected dual-motor build accelerates with explicit assumptions');
  assert.ok(+moving.distance>0&&+moving.energy>0&&+moving.soc<+stationary.soc);
  await page.keyboard.press('KeyC');assert.equal(await page.getByLabel('Driving camera').inputValue(),'chase');
  await page.keyboard.down('Space');
  await page.waitForFunction(start=>Number(document.querySelector('[data-testid="drive-telemetry"]')?.getAttribute('data-time'))>start+2,+moving.time);
  await page.keyboard.up('Space');
  const braked=await read();assert.ok(Math.abs(+braked.speed)<Math.abs(+moving.speed),'Brakes reduce speed');
  await page.keyboard.press('KeyP');await page.getByRole('button',{name:'Resume driving',exact:true}).waitFor();
  const paused=await read();await page.waitForTimeout(400);assert.deepEqual(await read(),paused,'Pause freezes physics, wheels, distance and energy');
  await mkdir('../docs/screenshots',{recursive:true});
  await page.screenshot({path:'../docs/screenshots/test-drive-track.png'});
  await page.keyboard.press('KeyC');assert.equal(await page.getByLabel('Driving camera').inputValue(),'free');
  await page.keyboard.press('KeyR');assert.equal(+(await read()).distance,0,'Reset clears drive telemetry');
  await page.getByRole('button',{name:'Engineering details',exact:true}).click();
  await page.getByLabel('Installed vehicle mass (without people)').fill('300');
  assert.equal(await page.getByRole('button',{name:'Start / resume',exact:true}).isDisabled(),true,'Changed assumptions require controlled reset');
  await page.getByRole('button',{name:'Apply inputs & reset',exact:true}).click();
  const library=await (await page.request.get(`${base}/api/components`)).json();
  // Emulate a newly saved builder/component selection without changing the
  // user's database; the runtime still fetches through its normal refresh API.
  const refreshed=structuredClone(library);const updated=refreshed.find(p=>p.id==='team-drive-wheel-direct');
  updated.specs.gear_ratio=2;
  await page.route('**/api/components',route=>route.fulfill({json:refreshed}));
  await page.getByRole('button',{name:'Refresh saved build',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('.drive-apply button')].some(b=>b.textContent==='Refresh saved build'&&!b.disabled));
  await page.getByRole('button',{name:'Apply inputs & reset',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Start / resume',exact:true}).isDisabled(),false,'Applied refreshed inputs are ready');
  assert.match(await page.locator('.drive-config-summary').innerText(),/2:1/,'Changed saved part enters the refreshed driving configuration');
  await page.unroute('**/api/components');
  await page.getByRole('button',{name:'Close engineering details'}).click();
  assert.equal(await page.getByLabel('Driving environment').locator('option').count(),7,'All driving courses are selectable');
  for(const environment of ['hills','terrain','circuit','city','slalom','rally']){
    await page.getByLabel('Driving environment').selectOption(environment);
    assert.equal(+(await read()).distance,0,`${environment}: switching courses resets distance`);
    assert.equal(await page.getByRole('button',{name:'Start / resume',exact:true}).isVisible(),true);
    assert.equal(await page.locator('.drive-course-guide').getAttribute('data-course'),environment);
    await page.getByRole('button',{name:'Start / resume',exact:true}).click();
    await page.waitForFunction(()=>Number(document.querySelector('[data-testid="drive-telemetry"]')?.getAttribute('data-time'))>1);
    assert.equal(+(await read()).contacts,4,`${environment}: real wheel contacts`);
    if(['circuit','city','slalom','rally'].includes(environment))await page.screenshot({path:`../docs/screenshots/test-drive-course-${environment}.png`});
  }
  await page.setViewportSize({width:390,height:844});
  assert.equal(await drive.evaluate(e=>e.scrollWidth>e.clientWidth),false,'No mobile horizontal overflow');
  await page.getByRole('button',{name:'Engineering details',exact:true}).click();
  await page.screenshot({path:'../docs/screenshots/test-drive-mobile.png'});
  await page.getByRole('button',{name:'Close engineering details'}).click();
  await page.getByLabel('Driving environment').selectOption('track');
  await page.getByLabel('Driving camera').selectOption('driver');
  await page.getByRole('button',{name:'Start / resume',exact:true}).click();
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  const accelerator=await page.getByRole('button',{name:'Accelerate',exact:true}).boundingBox();
  assert.ok(accelerator);
  const touchStart=+(await read()).time;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:accelerator.x+accelerator.width/2,y:accelerator.y+accelerator.height/2}]});
  await page.waitForFunction(start=>Number(document.querySelector('[data-testid="drive-telemetry"]')?.getAttribute('data-time'))>start+2,touchStart);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.ok(+(await read()).speed>.05,'Holding the mobile accelerator drives the vehicle');
  await page.screenshot({path:'../docs/screenshots/test-drive-driver.png'});
  await page.keyboard.press('KeyP');
  await page.keyboard.press('Escape');await drive.waitFor({state:'detached'});
  await page.getByRole('region',{name:'Interactive vehicle explorer'}).waitFor();
  assert.deepEqual(errors,[]);
  assert.equal(await snapshot(),before,'Driving must not modify saved designs, parts or FASTSim results');
  console.log('PASS: selected dual-motor build, stationary contacts, acceleration, braking, three cameras, pause/reset, controlled refresh, seven selectable courses with route guides and real contacts, mobile touch controls, exit and unchanged records.');
}catch(error){console.log('Drive failure context',await page.locator('.test-drive').innerText().catch(()=>''));await page.screenshot({path:'../.test-tmp/test-drive-failure.png'}).catch(()=>{});throw error;}finally{await browser.close();}

import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080}});
page.setDefaultTimeout(20000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:8000',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Home Dashboard',exact:true}).waitFor();
 await page.getByText('Document-sourced vehicle draft',{exact:false}).waitFor();
 assert.equal(await page.getByLabel('Active design').inputValue(),'team-ev-belt');
 assert.equal(await page.locator('.metrics .metric').first().locator('strong').innerText(),'—kg');
 await page.getByText('$333',{exact:true}).waitFor();
 await page.locator('canvas').first().waitFor();
 await mkdir('../docs/screenshots',{recursive:true});
 await page.screenshot({path:'../docs/screenshots/team-draft.png',fullPage:true});
 await page.locator('nav').getByRole('button',{name:'Vehicle Builder',exact:true}).click();
 assert.equal(await page.getByLabel('Load design').inputValue(),'team-ev-belt');
 const mass=page.locator('label').filter({hasText:'Passenger + cargo / kg'}).locator('input');
 assert.equal(await mass.inputValue(),'');
 await page.getByRole('button',{name:'Save design',exact:true}).click();
 await page.getByText('Design saved.',{exact:true}).waitFor();
 await page.locator('nav').getByRole('button',{name:'3D Vehicle Viewer',exact:true}).click();
 await page.getByRole('button',{name:'battery / pending',exact:true}).click();
 await page.locator('.inspect').getByText('Battery pack / specifications pending',{exact:true}).waitFor();
 await page.locator('.inspect').getByText('Installed mass unknown',{exact:false}).waitFor();
 await page.getByRole('button',{name:'steering',exact:true}).click();
 await page.locator('.inspect').getByText('Provisional steering gearmotor / AliExpress 3256806630223349',{exact:true}).waitFor();
 await page.locator('.viewer').screenshot({path:'../docs/screenshots/team-viewer.png'});
 await page.getByRole('button',{name:/Purchase planning/}).click();
 await page.getByRole('row').filter({hasText:'Sony DualShock 4 / operator controller'}).waitFor();
 await page.locator('nav').getByRole('button',{name:'Simulation Lab',exact:true}).click();
 await page.getByText(/Simulation unavailable:/).waitFor();
 assert.equal(await page.getByRole('button',{name:'Run simulation',exact:true}).isDisabled(),true);
 const blocked=await page.request.post('http://127.0.0.1:8000/api/runs',{data:{vehicle_id:'team-ev-belt'}});
 assert.equal(blocked.status(),422);
 await page.locator('label').filter({hasText:'Vehicle design'}).locator('select').selectOption('demo-student-ev');
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Run simulation'&&!b.disabled));
 await page.getByRole('button',{name:'Run simulation',exact:true}).click();
 await page.getByRole('heading',{name:'Performance Results',exact:true}).waitFor();
 await page.locator('.js-plotly-plot').first().waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.locator('nav').getByRole('button',{name:'Home Dashboard',exact:true}).click();
 await page.getByText('$333',{exact:true}).waitFor();
 await page.screenshot({path:'../docs/screenshots/team-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Mobile overflow');
 assert.deepEqual(errors,[]);
 console.log('PASS: team draft loaded, unknown metrics preserved, draft saved, parts inspectable, procurement inventory separated, incomplete simulation blocked, independent demo still runs, mobile layout fits.');
}finally{await browser.close()}

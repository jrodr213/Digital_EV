import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

const base=process.env.EV_BASE_URL??'http://127.0.0.1:8000';
const browser=await chromium.launch({channel:process.env.EV_BROWSER??'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
page.setDefaultTimeout(20000);
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const snapshot=async()=>JSON.stringify(await Promise.all(['components','vehicles'].map(async path=>(await page.request.get(`${base}/api/${path}`)).json())));
await mkdir('../docs/screenshots',{recursive:true});
try{
 const before=await snapshot();
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Home Dashboard',exact:true}).waitFor();
 assert.equal(await page.getByLabel('Active design').inputValue(),'team-ev-belt');
 await page.getByText('Direct · 2WD',{exact:true}).waitFor();
 await page.locator('nav').getByRole('button',{name:'3D Vehicle Viewer',exact:true}).click();
 const explorer=page.getByRole('region',{name:'Interactive vehicle explorer'});
 await explorer.locator('canvas').waitFor();
 await explorer.getByRole('button',{name:'Explore Powertrain',exact:true}).click();
 const partNames=await explorer.locator('.explorer-component-list>button').allTextContents();
 assert.equal(partNames.length,3);
 assert.equal(partNames.some(name=>/chain|sprocket|belt|axle/i.test(name)),false);
 await explorer.getByRole('button',{name:'Exploded',exact:true}).click();
 assert.equal(await explorer.locator('.explorer-failure').count(),0);
 await explorer.screenshot({path:'../docs/screenshots/vehicle-direct-drive.png'});
 await explorer.getByRole('button',{name:'Inspect Direct wheel connections',exact:true}).click();
 await explorer.getByText('Each motor connects directly to one rear wheel at 1:1, without reduction gears or a shared drive axle.',{exact:true}).waitFor();
 await page.locator('nav').getByRole('button',{name:'Simulation Lab',exact:true}).click();
 const run=page.getByRole('button',{name:'Run simulation',exact:true});
 await page.getByText(/Simulation unavailable:/).waitFor();
 assert.ok(await run.isDisabled());
 const toggle=page.getByRole('checkbox',{name:'Demo mode — fill missing inputs'});
 await toggle.check();
 const demoRun=page.getByRole('button',{name:'Run demo simulation',exact:true});
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Run demo simulation'&&!b.disabled));
 assert.equal(await page.getByLabel('Driving cycle').inputValue(),'demo-cart');
 await page.getByText('36 V / 540 Wh',{exact:true}).waitFor();
 await page.getByText(/View \d+ demo input assumptions/).click();
 await page.getByRole('row').filter({hasText:'rated_power_kw'}).filter({hasText:'1 kW'}).waitFor();
 assert.equal(await page.getByRole('row').filter({hasText:'gear_ratio'}).count(),0,'Known direct ratio must not be replaced by a demo reduction');
 await page.getByText(/View \d+ demo input assumptions/).click();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Demo lab mobile overflow');
 await page.getByText(/View \d+ demo input assumptions/).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Assumption table mobile overflow');
 await page.getByText(/View \d+ demo input assumptions/).click();
 await toggle.uncheck();
 await page.getByText(/Simulation unavailable:/).waitFor();
 assert.ok(await run.isDisabled(),'Turning demo off must restore required inputs');
 await toggle.check();
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Run demo simulation'&&!b.disabled));
 await page.setViewportSize({width:1440,height:1100});
 await page.screenshot({path:'../docs/screenshots/demo-lab.png',fullPage:true});
 const responsePromise=page.waitForResponse(response=>response.url().endsWith('/api/runs')&&response.request().method()==='POST');
 await demoRun.click();
 const response=await responsePromise;
 assert.equal(response.status(),200,await response.text());
 const result=await response.json();
 assert.equal(result.request.demo_mode,true);
 assert.equal(result.request.cycle,'demo-cart');
 assert.equal(result.assembly.specs.drivetrain.gear_ratio,1);
 assert.equal(result.analytical.can_start,false,'Assumed torque shortfall must remain visible');
 await page.getByRole('heading',{name:'Performance Results',exact:true}).waitFor();
 await page.getByText('DEMO ESTIMATE — your selected parts with assumed inputs',{exact:true}).waitFor();
 await page.getByText('Torque shortfall in the assumed configuration',{exact:true}).waitFor();
 await page.locator('.js-plotly-plot').first().waitFor();
 await page.screenshot({path:'../docs/screenshots/demo-results.png',fullPage:true});
 const reportHref=await page.getByRole('link',{name:'Export test report'}).getAttribute('href');
 const report=await page.request.get(`${base}${reportHref}`);
 assert.equal(report.status(),200);
 assert.match(await report.text(),/demo_assumptions/);
 const csvHref=await page.getByRole('link',{name:'Download CSV'}).getAttribute('href');
 const csv=await page.request.get(`${base}${csvHref}`);
 assert.match(await csv.text(),/^time_s,/);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Results mobile overflow');
 await page.locator('nav').getByRole('button',{name:'Saved Projects',exact:true}).click();
 const historyRow=page.getByRole('row').filter({hasText:'DEMO ESTIMATE'}).filter({hasText:'DEMO-CART'}).last();
 await historyRow.getByRole('button',{name:/View/}).click();
 await page.getByText('DEMO ESTIMATE — your selected parts with assumed inputs',{exact:true}).waitFor();
 assert.equal(await snapshot(),before,'Demo and viewer must not modify the saved build or library');
 assert.deepEqual(errors,[],'Browser runtime errors');
 console.log(`PASS: direct 2WD view, demo on/off, assumptions, actual FASTSim run ${result.id}, torque warning, charts, exports, history, mobile and unchanged saved inputs.`);
}catch(error){await page.screenshot({path:'../docs/screenshots/demo-failure.png',fullPage:true}).catch(()=>{});throw error}
finally{await browser.close()}

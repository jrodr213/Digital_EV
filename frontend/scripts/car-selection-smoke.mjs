import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

const base=process.env.EV_BASE_URL??'http://127.0.0.1:8000';
const browser=await chromium.launch({channel:process.env.EV_BROWSER??'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
page.setDefaultTimeout(20000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const snapshot=async()=>JSON.stringify(await Promise.all(['components','vehicles','results'].map(async path=>(await page.request.get(`${base}/api/${path}`)).json())));
const nav=name=>page.locator('nav').getByRole('button',{name,exact:true});
const choose=async name=>{await page.getByLabel('Choose a car',{exact:true}).selectOption({label:name});await page.getByRole('button',{name:'Open car',exact:true}).click()};
const explorer=page.getByRole('region',{name:'Interactive vehicle explorer'});
try{
 const before=await snapshot();
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Choose your car.',exact:true}).waitFor();
 await page.getByLabel('Choose a car',{exact:true}).waitFor();
 assert.equal(await page.locator('nav').count(),0,'Car selection precedes workspace navigation');
 assert.equal(await page.getByRole('button',{name:'Open car',exact:true}).isDisabled(),true,'Choose a car before opening it');
 assert.equal(await page.locator('.car-card').count(),0,'Cars are listed in one dropdown');
 const cars=await (await page.request.get(`${base}/api/vehicles`)).json();
 assert.equal(await page.getByLabel('Choose a car',{exact:true}).locator('option').count(),cars.length+1,'All saved cars are available');
 await page.getByLabel('Choose a car',{exact:true}).selectOption('team-ev-single-motor');
 const card=page.locator('[data-vehicle-id="team-ev-single-motor"]');
 assert.match(await card.innerText(),/1 motor · 1,000 W/);
 assert.match(await card.innerText(),/36 V · 20 Ah · 720 Wh/);
 await mkdir('../docs/screenshots',{recursive:true});
 await page.screenshot({path:'../docs/screenshots/car-selection.png',fullPage:true});
 await choose('Single-motor car');
 assert.equal(await page.getByLabel('Active design').inputValue(),'team-ev-single-motor');
 await explorer.locator('canvas').waitFor();
 assert.match(await explorer.locator('.explorer-spec-strip').innerText(),/1 motor/);
 assert.match(await explorer.locator('.explorer-spec-strip').innerText(),/Chain · 2WD/);
 await nav('Vehicle Builder').click();
 assert.equal(await page.getByLabel('Load design').inputValue(),'team-ev-single-motor');
 await nav('Simulation Lab').click();
 assert.equal(await page.getByLabel('Vehicle design',{exact:true}).inputValue(),'team-ev-single-motor');
 await page.getByText(/Simulation unavailable:/).waitFor();
 assert.equal(await page.getByRole('button',{name:'Run simulation',exact:true}).isEnabled(),false);
 await page.getByRole('checkbox',{name:/Demo mode/}).check();
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Run demo simulation'&&!b.disabled));
 const preview=await (await page.request.post(`${base}/api/runs/preview`,{data:{vehicle_id:'team-ev-single-motor',demo_mode:true}})).json();
 assert.equal(preview.specs.motor.rated_power_kw,1);
 assert.equal(preview.specs.battery.capacity_ah,20);
 assert.equal(preview.nominal_energy_kwh,.72);
 assert.ok(preview.demo_assumptions.some(a=>a.field==='gear_ratio'));
 await nav('3D Vehicle Viewer').click();
 assert.equal(await page.getByLabel('Visualized vehicle').inputValue(),'team-ev-single-motor');
 await explorer.getByRole('button',{name:'Explore Powertrain',exact:true}).click();
 await explorer.getByRole('button',{name:'Inspect Traction motor',exact:true}).click();
 assert.equal(await explorer.getByRole('link',{name:'Open supplied product reference'}).getAttribute('href'),'https://www.aliexpress.us/item/3256806152602316.html');
 await explorer.getByRole('button',{name:'Back to Powertrain',exact:true}).click();
 await explorer.getByRole('button',{name:'Inspect Chain, rear axle & differential',exact:true}).click();
 assert.match(await explorer.innerText(),/gearing pending/);
 await explorer.getByRole('button',{name:'Back to Powertrain',exact:true}).click();
 await explorer.screenshot({path:'../docs/screenshots/single-motor-powertrain.png'});
 await page.getByRole('button',{name:'Change car',exact:true}).click();
 await choose('Original two-motor car');
 assert.equal(await page.getByLabel('Active design').inputValue(),'team-ev-belt');
 assert.match(await explorer.locator('.explorer-spec-strip').innerText(),/2 motors/);
 assert.match(await explorer.locator('.explorer-spec-strip').innerText(),/Direct · 2WD/);
 await nav('Simulation Lab').click();
 assert.equal(await page.getByLabel('Vehicle design',{exact:true}).inputValue(),'team-ev-belt');
 await page.getByLabel('Vehicle design',{exact:true}).selectOption('team-ev-single-motor');
 await nav('Vehicle Builder').click();
 assert.equal(await page.getByLabel('Load design').inputValue(),'team-ev-single-motor');
 await page.getByLabel('Load design').selectOption('team-ev-belt');
 await nav('Home Dashboard').click();
 assert.equal(await page.getByLabel('Active design').inputValue(),'team-ev-belt');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.getByLabel('Choose a car',{exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Chooser mobile overflow');
 await page.getByLabel('Choose a car',{exact:true}).selectOption('team-ev-single-motor');
 await page.screenshot({path:'../docs/screenshots/car-selection-mobile.png',fullPage:true});
 await choose('Single-motor car');
 await explorer.locator('canvas').waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Workspace mobile overflow');
 assert.equal(await explorer.locator('.explorer-failure').count(),0,'WebGL must render');
 assert.deepEqual(errors,[]);
 assert.equal(await snapshot(),before,'Selecting and inspecting cars must not alter saved records');
 console.log('PASS: dropdown chooser, disabled empty selection, all saved cars, single-motor parts and links, new pack preview, shared selection across Builder/Lab/Viewer, original car preserved, re-entry, desktop/mobile and unchanged saved records.');
}finally{await browser.close()}
